-- Lost Pet Board — Supabase schema
-- Run this in the Supabase SQL Editor (Dashboard -> SQL Editor -> New query)

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  status text not null default 'lost' check (status in ('lost', 'found', 'returned')),
  type text not null,
  name text,
  area text not null,
  note text not null,
  contact text not null,
  photo text default '🐾',
  created_at timestamptz not null default now()
);

-- Public read: anyone can see the board
alter table public.posts enable row level security;

drop policy if exists "Public read access" on public.posts;
create policy "Public read access"
  on public.posts for select
  using (true);

-- Public insert: anyone can post a pet (no login required)
drop policy if exists "Public insert access" on public.posts;
create policy "Public insert access"
  on public.posts for insert
  with check (true);

-- Public update: anyone can mark a pet as returned
drop policy if exists "Public update access" on public.posts;
create policy "Public update access"
  on public.posts for update
  using (true)
  with check (true);
